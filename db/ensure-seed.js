// يعبّي قاعدة البيانات بالبيانات التجريبية فقط لو كانت فاضية (مفيش أي مشرف).
// مفيد في الاستضافة المجانية (زي Hugging Face) اللي بتمسح قاعدة البيانات عند إعادة التشغيل،
// فتفضل حسابات التجربة موجودة دايمًا، ومن غير ما نمسح بيانات موجودة بالفعل.

const db = require("./database");

const row = db.prepare(`SELECT COUNT(*) AS n FROM admins`).get();
if (!row || row.n === 0) {
  console.log("قاعدة البيانات فاضية، جارٍ تعبئتها بالبيانات التجريبية...");
  require("./seed");
} else {
  console.log("قاعدة البيانات فيها بيانات بالفعل، لن يتم تعديلها.");
}
